package com.gulshid.kotlinprogramming

fun main(args: Array<String>) {
    println("------ Unary Operator -------");
    var num : Double = 7.6;
    var ischeck : Boolean = true;

    println("The +Num  : ${+num}");
    println("The -Num  : ${-num}");
    println("The ++Num  : ${++num}");
    println("The --Num  : ${--num}");
    println("The !ischeck  : ${!ischeck}");

    println("--------------");
    var n : Double = 4.7;
    println("n++ ${n++}");
    println("n ${n}");
    println("++n ${++n}");
    println("n ${n}");




}